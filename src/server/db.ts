import { Database } from "bun:sqlite";
import { drizzle, type SQLiteBunDatabase } from "drizzle-orm/bun-sqlite";
import { migrate } from "drizzle-orm/bun-sqlite/migrator";
import { chmodSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { migrations } from "./migrations.generated.ts";

export function openDatabase(path: string): Database {
  if (path !== ":memory:" && !path.startsWith("file::memory:")) {
    mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  }
  const raw = new Database(path, { create: true });
  // Provider secrets are stored plaintext: the DB file is the security boundary.
  if (!path.startsWith("file::memory:")) {
    try {
      chmodSync(path, 0o600);
    } catch {
      // best effort (e.g. an unprivileged owner on a network filesystem)
    }
  }
  raw.exec("PRAGMA foreign_keys = ON;");
  raw.exec("PRAGMA journal_mode = WAL;");
  raw.exec("PRAGMA busy_timeout = 5000;");
  return raw;
}

/**
 * Opens the database and applies every embedded migration. Migrations are
 * generated by drizzle-kit into `drizzle/` and embedded by
 * `scripts/embed-migrations.ts`, so the compiled binary needs no files on disk.
 */
export function createDb(path: string) {
  const raw = openDatabase(path);
  const db = drizzle({ client: raw });
  migrate(db, { migrationsJournal: migrations });
  return db;
}

export type AppDb = SQLiteBunDatabase;
