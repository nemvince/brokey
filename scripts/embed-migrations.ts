// Embeds `drizzle/*/migration.sql` into a TypeScript module so the compiled
// single-file executable can migrate without the migrations folder on disk.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type EmbeddedMigration = { name: string; timestamp: number; sql: string };

const root = join(import.meta.dir, "..");
const migrationsDir = join(root, "drizzle");
const outFile = join(root, "src/server/migrations.generated.ts");

function folderMillis(name: string): number {
  const year = Number(name.slice(0, 4));
  const month = Number(name.slice(4, 6)) - 1;
  const day = Number(name.slice(6, 8));
  const hour = Number(name.slice(8, 10));
  const minute = Number(name.slice(10, 12));
  const second = Number(name.slice(12, 14));
  if (
    [year, month, day, hour, minute, second].some(
      (part) => !Number.isFinite(part),
    )
  ) {
    throw new Error(
      `Migration folder "${name}" does not start with a YYYYMMDDHHMMSS timestamp.`,
    );
  }
  return Date.UTC(year, month, day, hour, minute, second);
}

if (existsSync(join(migrationsDir, "meta"))) {
  throw new Error(
    `${migrationsDir} uses the pre-1.0 drizzle-kit layout. Run \`drizzle-kit up\` and regenerate.`,
  );
}

const migrations: EmbeddedMigration[] = existsSync(migrationsDir)
  ? readdirSync(migrationsDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort()
      .flatMap((name) => {
        const file = join(migrationsDir, name, "migration.sql");
        if (!existsSync(file)) return [];
        return [
          {
            name,
            timestamp: folderMillis(name),
            sql: readFileSync(file, "utf8"),
          },
        ];
      })
  : [];

const contents = `// Generated by scripts/embed-migrations.ts — do not edit by hand.
// Regenerate with \`bun run db:generate\` (or \`bun run build\`).

export type EmbeddedMigration = { name: string; timestamp: number; sql: string };

export const migrations: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(outFile, contents);
console.log(
  `Embedded ${migrations.length} migration${migrations.length === 1 ? "" : "s"} into ${outFile.replace(`${root}/`, "")}`,
);
